rev <- data.frame(Date = as.Date(c("2025-01-01","2025-12-01","2026-01-01")), Year = c(2025,2025,2026), Month = c(1,12,1),
  Revenue = c(100,100,120), Gross_Profit = c(30,30,40), Customer = c("Alpha", "Beta", "Alpha"), Invoice_Ref = c("INV-A","INV-B","INV-C"))
po <- data.frame(Date=rev$Date,Year=rev$Year,Month=rev$Month,PO_Number=c("PO-A","PO-B","PO-C"))
ar <- data.frame(Txn_Date=rev$Date,Balance_Remaining=c(10,20,30),Days_Past_Due=c(0,10,20))
inv <- data.frame(Supplier=c("Supplier A","Supplier B"),Order_Status=c("Overdue","Open"))
last <- NULL
test_theme_server <- function(input, output, session) {
  selected_rev <- reactive({ if (identical(input$global_year,"2026")) rev[3,,drop=FALSE] else rev })
  selected_po <- reactive({ if (identical(input$global_year,"2026")) po[3,,drop=FALSE] else po })
  aurelis_theme_server(input,output,session,selected_rev,reactive(ar),selected_po,reactive(inv),
    reactive(rev),reactive(po),reactiveVal(1),function(page) last <<- page,
    function(page) !identical(page,"executive_observatory"),updated_at=function()as.POSIXct("2026-01-01"))
}
shiny::testServer(test_theme_server, {
  session$setInputs(global_year="all",global_month="all",sidebar_tabs="exec_overview")
  stopifnot(grepl("Choose a year",output$v2_kpi_revenue$html,fixed=TRUE))
  stopifnot(grepl("no historical balance delta",output$v2_kpi_ar$html,fixed=TRUE))
  session$setInputs(global_year="2026",global_month="1")
  stopifnot(grepl("20.0%",output$v2_kpi_revenue$html,fixed=TRUE))
  stopifnot(grepl("Dec 2025",output$v2_kpi_revenue$html,fixed=TRUE))
  session$setInputs(v2_command=list(page="customer_performance",type="Client",label="Alpha"))
  stopifnot(identical(last,"customer_performance"))
  last <<- NULL
  session$setInputs(v2_command=list(page="customer_performance",type="Client",label="Unknown client"))
  stopifnot(is.null(last))
  session$setInputs(v2_command=list(page="executive_observatory"))
  stopifnot(is.null(last))
  session$setInputs(sidebar_tabs="analysis_lab")
  stopifnot(grepl("LAB SCOPE",output$v2_scope$html,fixed=TRUE))
  stopifnot(!grepl("v2_clear_year",output$v2_scope$html,fixed=TRUE))
})
message("PASS: calendar comparisons, missing/zero baselines, honest snapshot labeling, sparklines, command validation, access checks and independent Lab scope.")
